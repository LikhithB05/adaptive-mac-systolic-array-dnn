`timescale 1ns / 1ps

module adaptive_processing_element_tb;

/////////////////////////////////////////////////////////
// CLOCK RESET
/////////////////////////////////////////////////////////

reg clk;
reg reset;

/////////////////////////////////////////////////////////
// INPUTS
/////////////////////////////////////////////////////////

reg signed [31:0] A_in;
reg signed [31:0] B_in;

/////////////////////////////////////////////////////////
// OUTPUTS
/////////////////////////////////////////////////////////

wire signed [31:0] A_out;
wire signed [31:0] B_out;

wire signed [63:0] mac_out;

wire [1:0] mode_out;

/////////////////////////////////////////////////////////
// DUT
/////////////////////////////////////////////////////////

adaptive_processing_element uut(

    .clk(clk),
    .reset(reset),

    .A_in(A_in),
    .B_in(B_in),

    .A_out(A_out),
    .B_out(B_out),

    .mac_out(mac_out),

    .mode_out(mode_out)

);

/////////////////////////////////////////////////////////
// CLOCK
/////////////////////////////////////////////////////////

always #5 clk = ~clk;

/////////////////////////////////////////////////////////
// TEST
/////////////////////////////////////////////////////////

initial begin

    clk = 0;
    reset = 1;

    A_in = 0;
    B_in = 0;

    #20;

    reset = 0;

    /////////////////////////////////////////////////////
    // TEST 1 : 8-bit
    /////////////////////////////////////////////////////

    A_in = 10;
    B_in = 20;

    #20;

    /////////////////////////////////////////////////////
    // TEST 2 : 16-bit
    /////////////////////////////////////////////////////

    A_in = 1000;
    B_in = 20;

    #20;

    /////////////////////////////////////////////////////
    // TEST 3 : 32-bit
    /////////////////////////////////////////////////////

    A_in = 100000;
    B_in = 100;

    #20;

    /////////////////////////////////////////////////////
    // TEST 4 : Negative
    /////////////////////////////////////////////////////

    A_in = -50;
    B_in = 20;

    #20;

    $finish;

end

/////////////////////////////////////////////////////////
// MONITOR
/////////////////////////////////////////////////////////

initial begin

    $monitor(
    "t=%0t | Ain=%0d Bin=%0d | Aout=%0d Bout=%0d | MODE=%b | MAC=%0d",
    $time,
    A_in,
    B_in,
    A_out,
    B_out,
    mode_out,
    mac_out
    );

end

endmodule